BRANCH = re.compile(r"^(0x[0-9a-f]+)$")
MEM_ADDR = re.compile(r"\[((?:cs|ds|es|ss):)?(0x[0-9a-f]+)\]")
# Tables are always reached as base+displacement -- `[cs:bx + 0x457b]` -- so a
# pattern that only matches a bare `[0x457b]` leaves every table access in raw
# hex and makes symbol-based auditing blind to them.
MEM_INDEXED = re.compile(
    r"\[((?:cs|ds|es|ss):)?((?:[a-z]{2} \+ )+)(0x[0-9a-f]+)\]")


def build_labels(image, layout):
    """Name every branch/call target and record who references it.

    Cross-references are the cheapest real documentation available: they come
    straight from the disassembly, and knowing a routine has 26 callers tells
    you more about its role than a guessed name would.
    """
    labels = dict(NAMED_CODE)
    xrefs = {}
    calls = set()
    for addr, ins in layout.items():
        mn = ins.mnemonic.split()[-1]
        ops = ins.op_str
        if not (mn == "jmp" or mn == "call" or mn.startswith("j")
                or mn.startswith("loop")):
            continue
        if not BRANCH.match(ops):
            continue
        t = int(ops, 16)
        if not (ORG <= t < ORG + len(image)):
            continue
        xrefs.setdefault(t, set()).add(addr)
        if mn == "call":
            calls.add(t)
    for t in xrefs:
        if t not in labels:
            labels[t] = f"{'sub' if t in calls else 'loc'}_{t:04X}"
    return labels, xrefs


def apply_symbols(text, labels):
    """Swap numeric operands for label and constant names."""
    mn, _, ops = text.partition(" ")
    if ops and BRANCH.match(ops.strip()):
        t = int(ops.strip(), 16)
        if t in labels:
            return f"{mn} {labels[t]}"
    if "short " in text or "near " in text:
        head, _, tail = text.rpartition(" ")
        if BRANCH.match(tail):
            t = int(tail, 16)
            if t in labels:
                return f"{head} {labels[t]}"

    def sub_mem(m):
        seg, num = m.group(1) or "", m.group(2)
        name = NAMED_DATA.get(int(num, 16))
        return f"[{seg}{name or num}]"

    def sub_indexed(m):
        seg, regs, num = m.group(1) or "", m.group(2), m.group(3)
        name = NAMED_DATA.get(int(num, 16))
        return f"[{seg}{regs}{name or num}]"

    text = MEM_ADDR.sub(sub_mem, text)
    text = MEM_INDEXED.sub(sub_indexed, text)

    # Immediates that are known addresses, e.g. `mov dx, 0x102` loading the
    # "Tapper.Dat" filename pointer. Only the curated set is substituted, so a
    # plain constant that happens to share a value is never renamed.
    # `add ax, 0x5b1` in load_asset computes a table base, so the immediate
    # forms worth substituting are not only `mov`.
    m = re.match(r"^((?:mov|add) \w+, )(0x[0-9a-f]+)$", text)
    if m and int(m.group(2), 16) in NAMED_DATA:
        text = m.group(1) + NAMED_DATA[int(m.group(2), 16)]
    return text


def emit(image, layout, path):
    labels, xrefs = build_labels(image, layout)
    lines = [
        "; Tapper (IBM PC, 1984) -- reconstructed source",
        ";",
        "; Generated by tools/reconstruct.py and verified byte-identical",
        "; against the original TAPPER.COM after assembly.",
        ";",
        ";   nasm -f bin -o tapper.com tapper.asm",
        ";",
        "; Regions still emitted as `db` are data (strings, tables, jump",
        "; tables, padding) or bytes whose original encoding NASM does not",
        "; reproduce. See FINDINGS.md for the analysis behind the names.",
        "",
        "bits 16",
        "org 0x100",
        "",
        "; ---- named locations ----",
    ]
    for a, nm in sorted(NAMED_DATA.items()):
        if a not in labels:
            lines.append(f"{nm:<24} equ 0x{a:04X}")
    lines.append("")

    i, n = 0, len(image)
    while i < n:
        addr = i + ORG
        if addr in labels:
            lines.append("")
            doc = ROUTINE_DOCS.get(addr)
            if doc:
                lines.append("; " + "-" * 68)
                for d in doc:
                    lines.append(f"; {d}".rstrip())
                lines.append("; " + "-" * 68)
            refs = sorted(xrefs.get(addr, ()))
            if refs:
                shown = ", ".join(f"{r:04X}" for r in refs[:6])
                more = f", +{len(refs)-6} more" if len(refs) > 6 else ""
                lines.append(f"; xref: {shown}{more}"
                             f"   ({len(refs)} site{'s' if len(refs) > 1 else ''})")
            lines.append(f"{labels[addr]}:")
        ins = layout.get(addr)
        if ins is not None:
            body = apply_symbols(to_nasm(ins), labels)
            lines.append(f"    {body:<44}; {addr:04X}  {ins.bytes.hex().upper()}")
            i += ins.size
            continue
        # Data run, broken wherever a label lands inside it.
        start = i
        i += 1
        while i < n and (i + ORG) not in layout and (i + ORG) not in labels:
            i += 1
        blob = image[start:i]
        for off in range(0, len(blob), 16):
            chunk = blob[off:off + 16]
            hexs = ", ".join(f"0x{b:02X}" for b in chunk)
            lines.append(f"    db {hexs:<70}; {start + off + ORG:04X}")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def assemble(nasm, asm_path, bin_path):
    r = subprocess.run([nasm, "-f", "bin", "-o", bin_path, asm_path],
                       capture_output=True, text=True)
    return r.returncode == 0, r.stderr.strip()


def promote(image, seen, banned, nasm, asm_path, bin_path):
    """Recover instructions that were demoted for someone else's mistake.

    Demotion is greedy: each pass blames the instruction at the first differing
    byte. When an earlier instruction changes size, later ones can get demoted
    even though their own encoding was fine -- and once demoted they stay that
    way. So after the build is green, try putting them back.

    Testing 100+ candidates one at a time is wasteful, so this bisects: try a
    whole group at once, and only split it when the group fails.
    """
    def green(candidate_banned):
        layout = build_layout(seen, candidate_banned)
        emit(image, layout, asm_path)
        ok, _ = assemble(nasm, asm_path, bin_path)
        if not ok:
            return False
        return open(bin_path, "rb").read() == image

    tries = [0]

    def minimise(current, group):
        if not group:
            return current
        tries[0] += 1
        if green(current - set(group)):
            return current - set(group)
        if len(group) == 1:
            return current
        mid = len(group) // 2
        cur = minimise(current, group[:mid])
        return minimise(cur, group[mid:])

    before = len(banned)
    result = minimise(set(banned), sorted(banned))
    print(f"  promotion: recovered {before - len(result)}/{before} demoted "
          f"instructions in {tries[0]} test builds")
    return result


def main():
    nasm = find_nasm()
    if not nasm:
        print("nasm not found -- install it or add it to PATH")
        return
    image = open(SRC, "rb").read()
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(SRCDIR, exist_ok=True)
    asm_path = os.path.join(SRCDIR, "tapper.asm")
    bin_path = os.path.join(OUT, "tapper.com")

    print("tracing...", flush=True)
    seen = full_trace(image)
    print(f"traced {len(seen)} instructions; converging encodings", flush=True)

    banned = set()
    for attempt in range(1, 2001):
        layout = build_layout(seen, banned)
        emit(image, layout, asm_path)
        ok, err = assemble(nasm, asm_path, bin_path)
        if not ok:
            # A line NASM cannot parse: find it, ban that address, retry.
            m = re.search(r":(\d+):", err)
            hit = None
            if m:
                ln = int(m.group(1))
                text = open(asm_path).readlines()[ln - 1]
                a = re.search(r";\s*([0-9A-F]{4})\s", text)
                if a:
                    hit = int(a.group(1), 16)
            if hit is None or hit in banned:
                print(f"assembly failed and could not localise:\n{err[:400]}")
                return
            banned.add(hit)
            print(f"pass {attempt}: NASM rejected CS:{hit:04X}, demoting to db")
            continue

        out = open(bin_path, "rb").read()
        if out == image:
            print(f"pass {attempt}: BYTE-IDENTICAL, {len(banned)} demoted")
            banned = promote(image, seen, banned, nasm, asm_path, bin_path)
            layout = build_layout(seen, banned)
            emit(image, layout, asm_path)
            assemble(nasm, asm_path, bin_path)
            final = open(bin_path, "rb").read()
            assert final == image, "promotion broke the build"

            code_bytes = sum(i.size for i in layout.values())
            pct = code_bytes * 100 / len(image)
            print(f"\n  real instructions : {len(layout)}")
            print(f"  bytes as code     : {code_bytes}/{len(image)} ({pct:.1f}%)")
            print(f"  bytes as db       : {len(image)-code_bytes}")
            print(f"  still demoted     : {len(banned)}")
            # Record what NASM still will not reproduce, so the encoding gaps
            # can be attacked by pattern rather than one at a time.
            dpath = os.path.join(OUT, "demoted.txt")
            with open(dpath, "w") as f:
                for addr in sorted(banned):
                    ins = seen.get(addr)
                    if ins is None:
                        f.write(f"{addr:04X}  (no decode)\n")
                        continue
                    f.write(f"{addr:04X}  {ins.bytes.hex().upper():<12} "
                            f"{to_nasm(ins)}\n")
            print(f"\n  source  -> {asm_path}")
            print(f"  binary  -> {bin_path}")
            print(f"  demoted -> {dpath}")
            return

        # Demote only the instruction at the FIRST difference. Anything after it
        # is usually just shift from a size change, so demoting the whole tail
        # would throw away thousands of instructions that are actually fine.
        first = next((k for k in range(min(len(out), len(image)))
                      if out[k] != image[k]), min(len(out), len(image)))
        a = first + ORG
        hit = next((addr for addr, ins in layout.items()
                    if addr <= a < addr + ins.size), None)
        if hit is None or hit in banned:
            print(f"pass {attempt}: first difference at CS:{a:04X} is not "
                  f"inside a demotable instruction -- stopping")
            return
        banned.add(hit)
        if attempt % 25 == 0 or attempt < 5:
            print(f"pass {attempt}: first diff CS:{a:04X}, demoted "
                  f"{len(banned)} so far", flush=True)

    print("did not converge within the attempt limit")


if __name__ == "__main__":
    main()
