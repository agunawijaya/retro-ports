"""Always-green reconstruction of TAPPER.COM into NASM source.

The point is to never be in a state where correctness is unknown. Instead of
disassembling everything and hoping it reassembles, we emit source that is
byte-identical from the very first run:

  1. emit real instructions where we understand the code, `db` blobs elsewhere
  2. assemble with NASM and compare against the original
  3. any instruction NASM encodes differently gets demoted to `db`, and we
     regenerate -- so the build converges to byte-identical automatically

That makes "how much is real code" a measurable progress number rather than a
promise, and every future step keeps the hash green.

x86 has several encodings for the same instruction (`add ax,1` is both 05 01 00
and 83 C0 01), so demotion is expected on some instructions; those are the ones
to refine later with explicit size/short/near hints.

Usage:
    python reconstruct.py            # build and verify
"""
