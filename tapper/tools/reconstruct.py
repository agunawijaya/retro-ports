# String instructions: capstone spells out the implicit operands, NASM does not.
STRING_OPS = ("movs", "stos", "lods", "scas", "cmps", "ins", "outs")
SEG_BRACKET = re.compile(r"\b(cs|ds|es|ss):\[([^\]]*)\]")


def find_nasm():
    for c in NASM_CANDIDATES:
        try:
            subprocess.run([c, "-v"], capture_output=True, check=True)
            return c
        except (OSError, subprocess.CalledProcessError):
            continue
    return None


# Accumulator-with-imm16 opcodes (add/or/adc/sbb/and/sub/xor/cmp ax,imm16 and
# test ax,imm16), plus the 0x81 group. NASM shortens these to the sign-extended
# imm8 form whenever the value fits, which changes the byte length.
ACC_IMM16 = {0x05, 0x0D, 0x15, 0x1D, 0x25, 0x2D, 0x35, 0x3D, 0xA9}
PREFIXES = {0x26, 0x2E, 0x36, 0x3E, 0xF0, 0xF2, 0xF3, 0x66, 0x67}
LAST_IMM = re.compile(r",\s*(0x[0-9a-f]+|\d+)$")


def opcode_of(ins):
    for b in ins.bytes:
        if b not in PREFIXES:
            return b
    return None


def to_nasm(ins):
    """Translate one capstone instruction into NASM syntax."""
    mn, ops = ins.mnemonic, ins.op_str

    op = opcode_of(ins)

    # Two attempts were made here to restore displacement widths that NASM
    # shortens -- an explicit zero disp8 in `mov bp, [bx+0]`, and a disp16 that
    # would fit in a byte. Both regressed and both were reverted:
    #
    #   general ModR/M rule    59 -> 86 demotions
    #   limited to mov opcodes 54 -> 118 demotions
    #
    # The second was expected to be safe because those opcodes always carry a
    # ModR/M byte, so the failure is not about opcode selection: forcing the
    # width changes instructions that were already assembling correctly, faster
    # than it fixes the handful that were not. The remaining displacement cases
    # stay as `db`; they cost 13 instructions and are not worth another try
    # without a way to test one instruction at a time.

    # D0/D1 shift and rotate forms take an implicit count of 1 that capstone
    # leaves off; without it NASM assembles the CL-count form instead.
    if op in (0xD0, 0xD1) and "," not in ops:
        ops += ", 1"

    # A segment override on a string instruction is part of the encoding.
    if op in (0xAC, 0xAD, 0xA4, 0xA5, 0xA6, 0xA7) and ins.bytes[0] in (
            0x26, 0x2E, 0x36, 0x3E):
        seg = {0x26: "es", 0x2E: "cs", 0x36: "ss", 0x3E: "ds"}[ins.bytes[0]]
        return f"{seg} {mn}"

    # 0x98/0x99 are CBW/CWD in 16-bit mode. Capstone labels them with the
    # 32-bit names, and NASM assembles those to two bytes (66 98) instead of
    # one, so every occurrence would be demoted.
    if op == 0x98 and ins.size == 1:
        return "cbw"
    if op == 0x99 and ins.size == 1:
        return "cwd"

    # Keep the wide immediate form the original used.
    if op in ACC_IMM16 or op == 0x81:
        m = LAST_IMM.search(ops)
        if m:
            v = int(m.group(1), 0)
            if -128 <= (v - 0x10000 if v > 0x7FFF else v) <= 127:
                ops = ops[:m.start()] + f", strict word {m.group(1)}"

    # capstone prints `xchg bx, dx` for 87 D3, but NASM canonicalises the
    # operand order and emits the other encoding; swapping restores it.
    if mn == "xchg" and "," in ops and "[" not in ops:
        a, b = (t.strip() for t in ops.split(",", 1))
        ops = f"{b}, {a}"

    # `repne movsw word ptr es:[di], word ptr [si]` -> `repne movsw`
    bare = mn.split()[-1] if " " in mn else mn
    if bare.startswith(STRING_OPS) and len(bare) <= 6:
        return mn

    ops = ops.replace(" ptr ", " ")
    ops = SEG_BRACKET.sub(r"[\1:\2]", ops)

    # capstone uses ljmp/lcall for far transfers; NASM just wants jmp/call
    if mn in ("ljmp", "lcall"):
        mn = mn[1:]

    # NASM picks the near form for a forward `jmp` even when the original used
    # the 2-byte short form (E9 0D 00 instead of EB 0E), so state the width
    # explicitly. Without this every short branch gets demoted to db.
    if ops.startswith("0x") and "," not in ops:
        if mn == "jmp":
            mn = "jmp short" if ins.size == 2 else "jmp near"
        elif mn == "call":
            mn = "call near" if ins.size == 3 else mn
        elif mn[0] == "j" or mn.startswith("loop"):
            if ins.size == 2:
                mn = f"{mn} short"

    return f"{mn} {ops}".strip()


def executed_seeds(image):
    """Instruction addresses the emulator actually executed.

    Static recursive descent cannot reach code that is only entered through the
    interrupt vector table -- the INT 09h keyboard handler at 33A5 and the
    INT 1Ch timer handler at 3758 are installed by writing the IVT, so nothing
    ever "calls" them. Addresses recorded during emulation are, by definition,
    real instruction boundaries, which makes them safe seeds.
    """
    path = os.path.join(ROOT, "out", "executed.txt")
    if not os.path.exists(path):
        return set()
    out = set()
    for line in open(path):
        parts = line.split()
        if parts:
            a = int(parts[0], 16)
            if ORG <= a < ORG + len(image):
                out.add(a)
    return out


def full_trace(image):
    """Recursive descent plus indirect-target seeding, run once and reused."""
    entries = set([ORG] + disasm.EXTRA_ENTRIES) | executed_seeds(image)
    seen, _ = disasm.trace(image, entries)
    for _ in range(12):
        new = disasm.harvest(image, seen) - entries
        if not new:
            break
        entries |= new
        seen, _ = disasm.trace(image, entries)
    return seen


def build_layout(seen, banned):
    """Pick a non-overlapping instruction layout, skipping banned addresses."""
    layout, end = {}, ORG
    for addr in sorted(seen):
        if addr < end or addr in banned:
            continue
        ins = seen[addr]
        # Zero padding decodes as `add [bx+si],al`; keep it as data.
        if ins.bytes[:2] == b"\x00\x00":
            continue
        layout[addr] = ins
        end = addr + ins.size
    return layout


